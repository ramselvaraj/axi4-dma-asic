#!/usr/bin/env python3
"""Mutation check of the UVM testbench: inject each RTL bug from mutation/mutate_dma.py (plus the D1 regression) into a
scratch copy of the RTL, run dma_full_test under xsim, and report whether the UVM environment flags it.

  uvm/uvm_mutate.py [--jobs 8] [--xfers 40] [--only NAME] [--report uvm/mutation_matrix.md]

KILLED = UVM_ERROR/UVM_FATAL, a simulator crash, or a timeout. The unmodified RTL must pass first.
"""
import argparse, importlib.util, os, re, shutil, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
V = os.environ.get("VIVADO_BIN", "/mnt/windows/vivado_linux/2026.1/Vivado/bin")
spec = importlib.util.spec_from_file_location("mutate_dma", f"{ROOT}/mutation/mutate_dma.py")
md = importlib.util.module_from_spec(spec); spec.loader.exec_module(md)
RTL = md.RTL
EXTRA = [("regs_dst_align_ok", "regs", "dma_regs.sv", "(dst_addr[2:0] != 3'd0) ||", "1'b0 ||"),
         ("d1_overflow_check_removed", "regs", "dma_regs.sv",
          "||\n                 // D1: reject transfers that would run past 4 GiB (the address counters would wrap to 0)\n"
          "                 (({1'b0, src_addr} + {1'b0, len}) > 33'h1_0000_0000) ||\n"
          "                 (({1'b0, dst_addr} + {1'b0, len}) > 33'h1_0000_0000);", ";"),
         ("d1_only_src_checked", "regs", "dma_regs.sv",
          " ||\n                 (({1'b0, dst_addr} + {1'b0, len}) > 33'h1_0000_0000);", ";")]

def run(m, xfers):
    name, area, f, old, new = m
    work = tempfile.mkdtemp(prefix=f"um_{name}_")
    try:
        for x in RTL + ["tb/axi4_mem_model.sv"] + [f"uvm/{u}" for u in os.listdir(HERE) if u.endswith((".sv", ".svh"))]:
            os.makedirs(os.path.dirname(f"{work}/{x}"), exist_ok=True); shutil.copy(f"{ROOT}/{x}", f"{work}/{x}")
        if f:
            p = f"{work}/rtl/{f}"; s = open(p).read()
            if s.count(old) != 1: return name, area, "BAD-PATTERN", f"pattern occurs {s.count(old)}x"
            open(p, "w").write(s.replace(old, new))
        env = dict(os.environ, PATH=f"{V}:{os.environ['PATH']}")
        files = [f"{work}/{x}" for x in RTL] + [f"{work}/tb/axi4_mem_model.sv", f"{work}/uvm/dma_if.sv", f"{work}/uvm/dma_uvm_pkg.sv", f"{work}/uvm/tb_top.sv"]
        c = subprocess.run([f"{V}/xvlog", "-sv", "-L", "uvm", *files, "-i", f"{work}/uvm"], cwd=work, capture_output=True, text=True, env=env)
        e = subprocess.run([f"{V}/xelab", "-L", "uvm", "tb_top", "-s", "sim", "-timescale", "1ns/1ps", "-debug", "off"], cwd=work, capture_output=True, text=True, env=env)
        if "Built simulation snapshot" not in e.stdout: return name, area, "BUILD-FAIL", (c.stdout + e.stdout)[-200:]
        try:
            r = subprocess.run([f"{V}/xsim", "sim", "-runall", "-sv_seed", "7", "-testplusarg", "UVM_TESTNAME=dma_full_test",
                                "-testplusarg", f"NUM_XFERS={xfers}"], cwd=work, capture_output=True, text=True, timeout=420, env=env)
        except subprocess.TimeoutExpired:
            return name, area, "KILLED", "wall-clock timeout"
        out = r.stdout + r.stderr
        if "FATAL_ERROR: Vivado Simulator kernel" in out: return name, area, "KILLED", "simulator abort"
        errs = re.findall(r"^UVM_ERROR .*?\[(\w+)\] (.*)$", out, re.M)
        fat = re.findall(r"^UVM_FATAL .*?\[(\w+)\] (.*)$", out, re.M)
        if fat: return name, area, "KILLED", f"[{fat[0][0]}] " + re.sub(r"[0-9a-fx]{4,}|\d+", "N", fat[0][1])[:70]
        if errs: return name, area, "KILLED", f"[{errs[0][0]}] " + re.sub(r"[0-9a-fx]{4,}|\d+", "N", errs[0][1])[:70]
        if "TEST PASSED" not in out: return name, area, "KILLED", "no PASS banner (hang?)"
        return name, area, "SURVIVED", ""
    finally:
        shutil.rmtree(work, ignore_errors=True)

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--jobs", type=int, default=8); ap.add_argument("--xfers", type=int, default=40)
    ap.add_argument("--only"); ap.add_argument("--report"); a = ap.parse_args()
    base = run(("baseline", "-", None, "", ""), a.xfers)
    print("baseline:", base[2], base[3], flush=True)
    if base[2] != "SURVIVED": sys.exit("baseline RTL must pass the UVM test")
    muts = [m for m in [x for x in md.M if x[0] != 'regs_dst_align_ok'] + EXTRA if not a.only or m[0] == a.only]
    res = []
    with ThreadPoolExecutor(a.jobs) as ex:
        for r in ex.map(lambda m: run(m, a.xfers), muts):
            res.append(r); print(f"{r[0]:28s} {r[2]:9s} {r[3]}", flush=True)
    k = sum(r[2] == "KILLED" for r in res)
    print(f"\n== UVM environment killed {k}/{len(res)} mutants; survivors: {[r[0] for r in res if r[2] != 'KILLED']}")
    if a.report:
        with open(a.report, "w") as f:
            f.write(f"# UVM mutation matrix\n\nGenerated by `uvm/uvm_mutate.py` (xsim, dma_full_test, {a.xfers} transfers/sequence, seed 7).\n"
                    f"{k}/{len(res)} mutants killed.\n\n| Mutant | Area | Result | First UVM check that fired |\n|---|---|---|---|\n")
            for r in res: f.write(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |\n")
